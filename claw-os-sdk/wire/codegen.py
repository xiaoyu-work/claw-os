def ts_type(schema: dict, defs: dict, ctx: str) -> str:
    if "$ref" in schema:
        ref = schema["$ref"].split("/")[-1]
        return _camel(ref)
    if "oneOf" in schema or "anyOf" in schema:
        return "unknown"
    if "const" in schema:
        v = schema["const"]
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, int):
            return str(v)
        # Emit a JSON-style double-quoted string literal. Python's
        # `repr` would produce single quotes (`'foo'`) which TypeScript
        # accepts but diverges from what the other generators emit.
        return json.dumps(v)
    t = schema.get("type")
    if isinstance(t, list):
        return "unknown"
    if t == "string":
        if "enum" in schema:
            return " | ".join(json.dumps(e) for e in schema["enum"])
        return "string"
    if t == "integer" or t == "number":
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        return f"{ts_type(schema.get('items', {}), defs, ctx)}[]"
    if t == "object":
        if "properties" in schema:
            return _camel(ctx)
        return "Record<string, unknown>"
    return "unknown"


def ts_interface(name: str, schema: dict, defs: dict, out: list[str]) -> None:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    title = schema.get("title", name)
    description = schema.get("description", "")
    out.append("")
    out.append("/**")
    if title:
        out.append(f" * {title}.")
    for line in textwrap.wrap(description, 76):
        out.append(f" * {line}")
    out.append(" */")
    out.append(f"export interface {_camel(name)} {{")
    for pname, pschema in props.items():
        ty = ts_type(pschema, defs, f"{name}_{pname}")
        opt = "" if pname in required else "?"
        out.append(f"  {pname}{opt}: {ty};")
    out.append("}")


