#!/usr/bin/env python3
"""Codegen for claw-os-sdk wire/v1 schemas.

Reads every ``wire/v1/*.schema.json`` and emits typed bindings into each
language tree:

    rust/src/generated.rs            serde-friendly structs
    python/src/claw_os_sdk/generated.py    TypedDict definitions
    node/src/generated.ts            TypeScript interfaces
    go/generated.go                  Go structs

This is intentionally a small, hand-rolled emitter — no external generator
dependency. It handles the subset of JSON Schema used by wire/v1:

  - object with `properties` (+ `required`, `additionalProperties`)
  - primitive types: string, integer, number, boolean
    (`integer` follows JSON Schema mathematical semantics, so finite
    `1`, `1.0`, and `1e0` values are equivalent; bounds run afterward)
  - arrays (with `items`)
  - `enum` ⇒ becomes a string with a doc-listed allow-list (kept loose to
    stay forward-compatible with kernel additions). For Rust/Python/Go we
    additionally emit a runtime validator so a server emitting an
    out-of-spec value can be detected, not silently accepted.
  - `const` (used for the wire_version field)
  - $defs / $ref for in-file definitions
  - oneOf (rendered as JsonValue / Any / unknown / any)

Run from the SDK root:

    python3 wire/codegen.py
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import textwrap

ROOT = pathlib.Path(__file__).resolve().parent.parent
WIRE_DIR = ROOT / "wire" / "v1"
CONTRACT_PATH = WIRE_DIR / "contract.json"
RUST_OUT = ROOT / "rust" / "src" / "generated.rs"
PY_OUT   = ROOT / "python" / "src" / "claw_os_sdk" / "generated.py"
TS_OUT   = ROOT / "node" / "src" / "generated.ts"
GO_OUT   = ROOT / "go" / "generated.go"
CORE_MCP_OUT = ROOT.parent / "core" / "src" / "agent" / "tools" / "mcp" / "generated.rs"
CRATE_MCP_OUT = ROOT.parent / "crates" / "cos-mcp-serve" / "src" / "generated.rs"

BANNER_LINES = [
    "DO NOT EDIT BY HAND.",
    "Generated by claw-os-sdk/wire/codegen.py from wire/v1/*.schema.json.",
    "Run `python3 wire/codegen.py` from the SDK root to regenerate.",
]


# --- helpers -----------------------------------------------------------

def _camel(name: str) -> str:
    if "_" not in name and "-" not in name and name[:1].isupper():
        return name
    parts = name.replace("-", "_").split("_")
    return "".join(p.capitalize() for p in parts if p)


def _snake(name: str) -> str:
    out = []
    for i, ch in enumerate(name):
        if ch.isupper() and i and not name[i - 1].isupper():
            out.append("_")
        out.append(ch.lower())
    return "".join(out).replace("-", "_")


def _is_scalar_schema(schema: dict) -> bool:
    """Return True when the schema describes a scalar (string / number /
    integer / boolean). Used by the Go emitter to decide whether
    ``omitempty`` will actually do anything for an optional field.
    Go's ``omitempty`` is a no-op on non-pointer struct values: a
    zero-valued struct still serialises as ``{}``, which silently
    diverges from what the other SDKs emit. For non-scalar optional
    fields we emit a pointer type instead.
    """
    if "$ref" in schema:
        return False
    if "oneOf" in schema or "anyOf" in schema:
        # Rendered as `interface{}` which is already a reference type.
        return True
    if "const" in schema:
        return True
    t = schema.get("type")
    if isinstance(t, list):
        return True
    if t in ("string", "integer", "number", "boolean"):
        return True
    # Arrays in Go are slices (already nil-zero), and maps likewise —
    # `omitempty` works for them. Only inline object structs ("type":
    # "object" with properties) need a pointer wrapper.
    if t == "array":
        return True
    if t == "object" and "properties" not in schema:
        return True
    return False


def load_schemas() -> list[tuple[str, dict]]:
    schemas: list[tuple[str, dict]] = []
    for path in sorted(WIRE_DIR.glob("*.schema.json")):
        name = path.stem.replace(".schema", "")
        with path.open() as fh:
            schemas.append((name, json.load(fh)))
    return schemas


def load_contract() -> dict:
    with CONTRACT_PATH.open(encoding="utf-8") as fh:
        return json.load(fh)


def _schema_json(schema: dict) -> str:
    return json.dumps(schema, sort_keys=True, separators=(",", ":"))


def _validation_schemas(
    schemas: list[tuple[str, dict]], contract: dict
) -> list[tuple[str, dict]]:
    by_name = dict(schemas)
    names = contract["validation"]["schemas"]
    missing = [name for name in names if name not in by_name]
    if missing:
        raise ValueError(f"validation schema not found: {', '.join(missing)}")
    return [(name, by_name[name]) for name in names]


def _validation_targets(
    schemas: list[tuple[str, dict]], contract: dict
) -> list[tuple[str, dict]]:
    targets = _validation_schemas(schemas, contract)
    by_name = dict(schemas)
    for target in contract["validation"].get("targets", []):
        rule = by_name[target["schema"]]
        for component in target["path"]:
            rule = rule[component]
        targets.append((target["name"], rule))
    return targets


# --- rust --------------------------------------------------------------

def rust_type(schema: dict, defs: dict, ctx: str) -> str:
    if "x-rust-type" in schema:
        return schema["x-rust-type"]
    if "$ref" in schema:
        ref = schema["$ref"].split("/")[-1]
        return _camel(ref)
    if "oneOf" in schema or "anyOf" in schema:
        return "serde_json::Value"
    if "const" in schema:
        v = schema["const"]
        if isinstance(v, bool):
            return "bool"
        if isinstance(v, int):
            # Default to i64 — narrowing to u8 silently corrupts any
            # future const integer > 255 (a build number, an HTTP
            # status, etc.). Only emit the smaller type when the schema
            # explicitly constrains the value into a u8 range.
            mn = schema.get("minimum")
            mx = schema.get("maximum")
            if mn is not None and mx is not None and 0 <= mn and mx <= 255:
                return "u8"
            if mn is not None and mn >= 0:
                return "u64"
            return "i64"
        return "String"
    t = schema.get("type")
    if isinstance(t, list):
        return "serde_json::Value"
    if t == "string":
        return "String"
    if t == "integer":
        # No const, no bounds → i64 is the universally-safe default for
        # wire integers. Schemas that need a smaller type can declare
        # `minimum`/`maximum` and we'll narrow accordingly.
        mn = schema.get("minimum")
        mx = schema.get("maximum")
        if mn is not None and mx is not None and 0 <= mn and mx <= 255:
            return "u8"
        if mn is not None and mn >= 0:
            return "u64"
        return "i64"
    if t == "number":
        return "f64"
    if t == "boolean":
        return "bool"
    if t == "array":
        inner = rust_type(schema.get("items", {}), defs, ctx)
        return f"Vec<{inner}>"
    if t == "object":
        if "properties" in schema:
            return _camel(ctx)
        return "serde_json::Value"
    return "serde_json::Value"


def rust_struct(name: str, schema: dict, defs: dict, out: list[str]) -> None:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    title = schema.get("title", name)
    description = schema.get("description", "")
    doc = []
    if title:
        doc.append(f"/// {title}")
    for line in textwrap.wrap(description, 78):
        doc.append(f"/// {line}")
    if doc:
        out.extend(doc)
    out.append("#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]")
    out.append(f"pub struct {_camel(name)} {{")
    for pname, pschema in props.items():
        rust_ty = rust_type(pschema, defs, f"{name}_{pname}")
        rename = ""
        snake = _snake(pname)
        if snake != pname:
            rename = f'    #[serde(rename = "{pname}")]\n'
        if pname not in required:
            out.append(f'    #[serde(default, skip_serializing_if = "Option::is_none")]')
            out.append(f"{rename}    pub {snake}: Option<{rust_ty}>,")
        else:
            if rename:
                out.append(rename.rstrip())
            out.append(f"    pub {snake}: {rust_ty},")
    out.append("}")
    out.append("")


def emit_rust(schemas: list[tuple[str, dict]], contract: dict) -> str:
    body: list[str] = []
    body.append("// " + BANNER_LINES[0])
    for line in BANNER_LINES[1:]:
        body.append("// " + line)
    body.append("")
    body.append("#![allow(clippy::all)]")
    body.append("#![allow(non_snake_case, non_camel_case_types)]")
    body.append("")
    body.append("use serde_json;")
    body.append("")
    body.append(f"/// Expected wire-version value emitted by the kernel. The")
    body.append(f"/// generated [`Envelope`] type's runtime check accepts only")
    body.append(f"/// this constant; anything else is surfaced as an error.")
    expected_wire_version = contract["wire_version"]
    body.append(f"pub const EXPECTED_WIRE_VERSION: i64 = {expected_wire_version};")
    body.append("")
    body.append("/// Verify a deserialised envelope advertises a wire version this")
    body.append("/// SDK understands. Returns `Err(msg)` on mismatch.")
    body.append("///")
    body.append("/// Callers (typically `claw_os_sdk::envelope::Envelope::accept`)")
    body.append("/// should refuse to interpret the payload further when this")
    body.append("/// returns Err — a future kernel speaking wire/v2 must be")
    body.append("/// matched by an SDK that knows that protocol.")
    body.append("pub fn check_wire_version(seen: i64) -> Result<(), String> {")
    body.append("    if seen == EXPECTED_WIRE_VERSION {")
    body.append("        Ok(())")
    body.append("    } else {")
    body.append("        Err(format!(")
    body.append("            \"unsupported wire_version: got {}, expected {}\",")
    body.append("            seen, EXPECTED_WIRE_VERSION,")
    body.append("        ))")
    body.append("    }")
    body.append("}")
    body.append("")
    enum_validators: list[tuple[str, str, list]] = []
    for name, schema in schemas:
        rust_struct(name, schema, schema.get("$defs", {}), body)
        nested: list[tuple[str, dict]] = []
        _collect_nested(name, schema, nested)
        for nname, nschema in nested:
            rust_struct(nname, nschema, schema.get("$defs", {}), body)
        for def_name, def_schema in schema.get("$defs", {}).items():
            rust_struct(def_name, def_schema, {}, body)
        _collect_enum_validators(name, schema, enum_validators)
        for nname, nschema in nested:
            _collect_enum_validators(nname, nschema, enum_validators)
    for parent, field_name, values in enum_validators:
        fn = f"validate_{_snake(parent)}_{_snake(field_name)}"
        body.append(f"/// Reject values outside the {parent}.{field_name} enum.")
        body.append("///")
        body.append("/// The wire schema lists a closed set of allowed values; a kernel")
        body.append("/// that emits an unknown one should not be silently accepted.")
        body.append(f"pub fn {fn}(value: &str) -> Result<(), String> {{")
        rendered = ", ".join(f'"{v}"' for v in values)
        body.append(f"    const ALLOWED: &[&str] = &[{rendered}];")
        body.append("    if ALLOWED.iter().any(|a| *a == value) {")
        body.append("        Ok(())")
        body.append("    } else {")
        body.append(f"        Err(format!(\"invalid {parent}.{field_name} value: {{value}}\"))")
        body.append("    }")
        body.append("}")
        body.append("")
    _emit_rust_validation(body, _validation_targets(schemas, contract), contract)
    return "\n".join(body) + "\n"


def _collect_nested(name: str, schema: dict, acc: list[tuple[str, dict]]) -> None:
    """Walk properties / items and collect anonymous nested objects.

    Each entry produced has a fully-qualified ctx name (e.g. ``ai_usage``)
    matching what ``*_type`` helpers compute, so emitters can generate
    matching standalone struct / interface definitions for them.
    """
    props = schema.get("properties", {})
    for pname, pschema in props.items():
        ctx = f"{name}_{pname}"
        if pschema.get("type") == "object" and "properties" in pschema:
            acc.append((ctx, pschema))
            _collect_nested(ctx, pschema, acc)
        elif pschema.get("type") == "array":
            items = pschema.get("items", {})
            if items.get("type") == "object" and "properties" in items:
                acc.append((ctx, items))
                _collect_nested(ctx, items, acc)


def _collect_enum_validators(parent: str, schema: dict, acc: list) -> None:
    """Collect (parent, field, values) tuples for every string `enum`
    property — used to emit per-language runtime validators."""
    props = schema.get("properties", {})
    for pname, pschema in props.items():
        if pschema.get("type") == "string" and "enum" in pschema:
            acc.append((parent, pname, list(pschema["enum"])))


def _emit_rust_validation(
    body: list[str], schemas: list[tuple[str, dict]], contract: dict
) -> None:
    codes = contract["validation"]["error_codes"]
    body.extend([
        "/// Stable failure returned by generated wire validators.",
        "#[derive(Debug, Clone, PartialEq, Eq)]",
        "pub struct WireDecodeError {",
        "    pub code: &'static str,",
        "    pub schema: &'static str,",
        "    pub path: String,",
        "    pub reason: String,",
        "}",
        "",
        "impl std::fmt::Display for WireDecodeError {",
        "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {",
        "        write!(f, \"{}: invalid {} at {}: {}\", self.code, self.schema, self.path, self.reason)",
        "    }",
        "}",
        "",
        "impl std::error::Error for WireDecodeError {}",
        "",
    ])
    for key, value in codes.items():
        body.append(f'pub const WIRE_{key.upper()}: &str = "{value}";')
    body.extend([
        "",
        "fn wire_error(",
        "    code: &'static str,",
        "    schema: &'static str,",
        "    path: &str,",
        "    reason: impl Into<String>,",
        ") -> WireDecodeError {",
        "    WireDecodeError { code, schema, path: path.to_string(), reason: reason.into() }",
        "}",
        "",
        "fn validate_wire_schema(",
        "    rule: &serde_json::Value,",
        "    root: &serde_json::Value,",
        "    value: &serde_json::Value,",
        "    schema_name: &'static str,",
        "    path: &str,",
        ") -> Result<(), WireDecodeError> {",
        '    if let Some(reference) = rule.get("$ref").and_then(serde_json::Value::as_str) {',
        "        let name = reference.rsplit('/').next().unwrap_or_default();",
        '        let target = root.get("$defs").and_then(|defs| defs.get(name)).ok_or_else(|| {',
        '            wire_error(WIRE_TYPE, schema_name, path, format!("unresolved schema reference {reference}"))',
        "        })?;",
        "        return validate_wire_schema(target, root, value, schema_name, path);",
        "    }",
        '    if let Some(branches) = rule.get("oneOf").and_then(serde_json::Value::as_array) {',
        "        let matches = branches.iter().filter(|branch| {",
        "            validate_wire_schema(branch, root, value, schema_name, path).is_ok()",
        "        }).count();",
        "        if matches != 1 {",
        '            return Err(wire_error(WIRE_ONE_OF, schema_name, path, "expected exactly one allowed shape"));',
        "        }",
        "        return Ok(());",
        "    }",
        '    if let Some(expected) = rule.get("type").and_then(serde_json::Value::as_str) {',
        "        let valid = match expected {",
        '            "object" => value.is_object(),',
        '            "array" => value.is_array(),',
        '            "string" => value.is_string(),',
        '            "integer" => value.as_i64().is_some() || value.as_u64().is_some() || value.as_f64().is_some_and(|number| number.is_finite() && number.fract() == 0.0),',
        '            "number" => value.is_number(),',
        '            "boolean" => value.is_boolean(),',
        '            "null" => value.is_null(),',
        "            _ => false,",
        "        };",
        "        if !valid {",
        '            return Err(wire_error(WIRE_TYPE, schema_name, path, format!("expected {expected}")));',
        "        }",
        "    }",
        '    if let Some(expected) = rule.get("const") {',
        "        if value != expected {",
        '            return Err(wire_error(WIRE_CONST, schema_name, path, "value does not match const"));',
        "        }",
        "    }",
        '    if let Some(allowed) = rule.get("enum").and_then(serde_json::Value::as_array) {',
        "        if !allowed.contains(value) {",
        '            return Err(wire_error(WIRE_ENUM, schema_name, path, "value is not in the allowed enum"));',
        "        }",
        "    }",
        "    if let Some(number) = value.as_f64() {",
        '        if let Some(minimum) = rule.get("minimum").and_then(serde_json::Value::as_f64) {',
        "            if number < minimum {",
        '                return Err(wire_error(WIRE_MINIMUM, schema_name, path, format!("must be >= {minimum}")));',
        "            }",
        "        }",
        '        if let Some(maximum) = rule.get("maximum").and_then(serde_json::Value::as_f64) {',
        "            if number > maximum {",
        '                return Err(wire_error(WIRE_MAXIMUM, schema_name, path, format!("must be <= {maximum}")));',
        "            }",
        "        }",
        "    }",
        "    if let Some(object) = value.as_object() {",
        '        if let Some(required) = rule.get("required").and_then(serde_json::Value::as_array) {',
        "            for field in required {",
        "                let field = field.as_str().unwrap_or_default();",
        "                if !object.contains_key(field) {",
        "                    let field_path = format!(\"{path}.{field}\");",
        '                    return Err(wire_error(WIRE_REQUIRED, schema_name, &field_path, "field is required"));',
        "                }",
        "            }",
        "        }",
        '        if let Some(properties) = rule.get("properties").and_then(serde_json::Value::as_object) {',
        "            let mut names: Vec<&String> = properties.keys().collect();",
        "            names.sort();",
        "            for name in names {",
        "                if let Some(field_value) = object.get(name) {",
        "                    let field_path = format!(\"{path}.{name}\");",
        "                    validate_wire_schema(&properties[name], root, field_value, schema_name, &field_path)?;",
        "                }",
        "            }",
        "            let mut extras: Vec<&String> = object.keys().filter(|name| !properties.contains_key(*name)).collect();",
        "            extras.sort();",
        '            if rule.get("additionalProperties") == Some(&serde_json::Value::Bool(false)) {',
        "                if let Some(name) = extras.first() {",
        "                    let field_path = format!(\"{path}.{name}\");",
        '                    return Err(wire_error(WIRE_UNKNOWN_FIELD, schema_name, &field_path, "unknown field"));',
        "                }",
        '            } else if let Some(additional) = rule.get("additionalProperties").filter(|v| v.is_object()) {',
        "                for name in extras {",
        "                    let field_path = format!(\"{path}.{name}\");",
        "                    validate_wire_schema(additional, root, &object[name], schema_name, &field_path)?;",
        "                }",
        "            }",
        "        }",
        "    }",
        "    if let Some(items) = value.as_array() {",
        '        if let Some(item_rule) = rule.get("items") {',
        "            for (index, item) in items.iter().enumerate() {",
        "                let item_path = format!(\"{path}[{index}]\");",
        "                validate_wire_schema(item_rule, root, item, schema_name, &item_path)?;",
        "            }",
        "        }",
        "    }",
        "    Ok(())",
        "}",
        "",
        "fn normalize_wire_integers(",
        "    rule: &serde_json::Value,",
        "    root: &serde_json::Value,",
        "    value: &mut serde_json::Value,",
        ") {",
        '    if let Some(reference) = rule.get("$ref").and_then(serde_json::Value::as_str) {',
        "        let name = reference.rsplit('/').next().unwrap_or_default();",
        '        if let Some(target) = root.get("$defs").and_then(|defs| defs.get(name)) {',
        "            normalize_wire_integers(target, root, value);",
        "        }",
        "        return;",
        "    }",
        '    if let Some(branches) = rule.get("oneOf").and_then(serde_json::Value::as_array) {',
        "        if let Some(branch) = branches.iter().find(|branch| {",
        '            validate_wire_schema(branch, root, value, "generated", "$").is_ok()',
        "        }) {",
        "            normalize_wire_integers(branch, root, value);",
        "        }",
        "        return;",
        "    }",
        '    if rule.get("type").and_then(serde_json::Value::as_str) == Some("integer")',
        "        && value.as_i64().is_none()",
        "        && value.as_u64().is_none()",
        "    {",
        "        if let Some(number) = value.as_f64() {",
        "            if number >= 0.0 && number <= u64::MAX as f64 {",
        "                *value = serde_json::Value::Number(serde_json::Number::from(number as u64));",
        "            } else if number >= i64::MIN as f64 && number <= i64::MAX as f64 {",
        "                *value = serde_json::Value::Number(serde_json::Number::from(number as i64));",
        "            }",
        "        }",
        "        return;",
        "    }",
        "    if let Some(object) = value.as_object_mut() {",
        '        if let Some(properties) = rule.get("properties").and_then(serde_json::Value::as_object) {',
        "            for (name, field_rule) in properties {",
        "                if let Some(field_value) = object.get_mut(name) {",
        "                    normalize_wire_integers(field_rule, root, field_value);",
        "                }",
        "            }",
        '            if let Some(additional) = rule.get("additionalProperties").filter(|v| v.is_object()) {',
        "                for (name, field_value) in object {",
        "                    if !properties.contains_key(name) {",
        "                        normalize_wire_integers(additional, root, field_value);",
        "                    }",
        "                }",
        "            }",
        "        }",
        "    } else if let Some(items) = value.as_array_mut() {",
        '        if let Some(item_rule) = rule.get("items") {',
        "            for item in items {",
        "                normalize_wire_integers(item_rule, root, item);",
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ])
    for name, schema in schemas:
        const_name = f"_WIRE_SCHEMA_{name.upper()}"
        fn_name = f"validate_{_snake(name)}"
        body.append(f'const {const_name}: &str = r###"{_schema_json(schema)}"###;')
        body.append(f"pub fn {fn_name}(value: &serde_json::Value) -> Result<(), WireDecodeError> {{")
        body.append(f"    let schema: serde_json::Value = serde_json::from_str({const_name})")
        body.append('        .expect("generated wire schema must be valid JSON");')
        body.append(f'    validate_wire_schema(&schema, &schema, value, "{_camel(name)}", "$")')
        body.append("}")
        body.append("")
        body.append(
            f"pub fn normalize_{_snake(name)}_integers(value: &mut serde_json::Value) {{"
        )
        body.append(f"    let schema: serde_json::Value = serde_json::from_str({const_name})")
        body.append('        .expect("generated wire schema must be valid JSON");')
        body.append("    normalize_wire_integers(&schema, &schema, value);")
        body.append("}")
        body.append("")


# --- python ------------------------------------------------------------

def py_type(schema: dict, defs: dict, ctx: str) -> str:
    if "$ref" in schema:
        ref = schema["$ref"].split("/")[-1]
        return f'"{_camel(ref)}"'
    if "oneOf" in schema or "anyOf" in schema:
        return "Any"
    if "const" in schema:
        v = schema["const"]
        if isinstance(v, bool):
            return "bool"
        if isinstance(v, int):
            return "int"
        return "str"
    t = schema.get("type")
    if isinstance(t, list):
        return "Any"
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "array":
        inner = py_type(schema.get("items", {}), defs, ctx)
        return f"List[{inner}]"
    if t == "object":
        if "properties" in schema:
            return f'"{_camel(ctx)}"'
        return "Dict[str, Any]"
    return "Any"


def py_typed_dict(name: str, schema: dict, defs: dict, out: list[str]) -> None:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    title = schema.get("title", name)
    description = schema.get("description", "")
    public_name = _camel(name)
    required_props = [(pname, pschema) for pname, pschema in props.items() if pname in required]
    optional_props = [(pname, pschema) for pname, pschema in props.items() if pname not in required]
    out.append("")
    if required_props and optional_props:
        base_name = f"_{public_name}Required"
        out.append(f"class {base_name}(TypedDict):")
        for pname, pschema in required_props:
            ty = py_type(pschema, defs, f"{name}_{pname}")
            out.append(f"    {pname}: {ty}")
        out.append("")
        out.append(f"class {public_name}({base_name}, total=False):")
        fields = optional_props
    elif required_props:
        out.append(f"class {public_name}(TypedDict):")
        fields = required_props
    else:
        out.append(f"class {public_name}(TypedDict, total=False):")
        fields = optional_props
    out.append(f'    """{title}.')
    if description:
        out.append("")
        for line in textwrap.wrap(description, 76):
            out.append(f"    {line}")
    out.append('    """')
    if not fields:
        out.append("    pass")
        return
    for pname, pschema in fields:
        ty = py_type(pschema, defs, f"{name}_{pname}")
        out.append(f"    {pname}: {ty}")


