def go_type(schema: dict, defs: dict, ctx: str) -> str:
    if "x-go-type" in schema:
        return schema["x-go-type"]
    if "$ref" in schema:
        ref = schema["$ref"].split("/")[-1]
        return _camel(ref)
    if "oneOf" in schema or "anyOf" in schema:
        return "interface{}"
    if "const" in schema:
        return "int" if isinstance(schema["const"], int) else "string"
    t = schema.get("type")
    if isinstance(t, list):
        return "interface{}"
    if t == "string":
        return "string"
    if t == "integer":
        return "uint64" if schema.get("minimum", -1) >= 0 else "int64"
    if t == "number":
        return "float64"
    if t == "boolean":
        return "bool"
    if t == "array":
        return f"[]{go_type(schema.get('items', {}), defs, ctx)}"
    if t == "object":
        if "properties" in schema:
            return _camel(ctx)
        return "map[string]interface{}"
    return "interface{}"


def go_struct(name: str, schema: dict, defs: dict, out: list[str]) -> None:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    title = schema.get("title", name)
    description = schema.get("description", "")
    if title:
        out.append(f"// {_camel(name)} — {title}.")
    for line in textwrap.wrap(description, 78):
        out.append(f"// {line}")
    out.append(f"type {_camel(name)} struct {{")
    for pname, pschema in props.items():
        ty = go_type(pschema, defs, f"{name}_{pname}")
        is_required = pname in required
        omit = "" if is_required else ",omitempty"
        # Go's `omitempty` is a no-op on non-pointer struct values: a
        # zero-valued nested struct still serialises as `{}`, which
        # diverges from what the Python/Rust/TS SDKs emit (they omit
        # the field entirely). For optional object-type fields we emit
        # a pointer (`*T`) so `omitempty` actually skips the key when
        # the field is `nil`.
        if not is_required and not _is_scalar_schema(pschema):
            ty = f"*{ty}"
        field = "".join(p.capitalize() for p in pname.replace("-", "_").split("_"))
        out.append(f'\t{field} {ty} `json:"{pname}{omit}"`')
    out.append("}")
    out.append("")


